"""Benchmark loaders returning (x, y) with shape (n, *grid, channels), float32."""
import inspect
import os
import numpy as np
import torch
from sgpo.data.readers import MatReader

_ROOT = os.path.join(os.path.dirname(__file__), "..", "..", "datasets")
RAW = os.environ.get("LOGOS_RAW", os.path.join(_ROOT, "raw"))


def _npy(path):
    return np.load(path, mmap_mode="r", allow_pickle=False)


def ns_forcing(n):
    """de Hoop et al. 2022: forcing -> vorticity at T=10, nu=0.025, 64x64, N=40000."""
    a = _npy(f"{RAW}/caltech/NavierStokes_inputs.npy")[..., :n]
    u = _npy(f"{RAW}/caltech/NavierStokes_outputs.npy")[..., :n]
    f = lambda v: torch.from_numpy(np.array(v, dtype=np.float32)).permute(2, 1, 0)[..., None]
    return f(a), f(u)


def burgers(n, sub=8):
    """Li et al. 2021: u0 -> u(T=1), nu=0.1, 8192 points subsampled to 1024."""
    r = MatReader(f"{RAW}/fno/burgers/burgers_data_R10.mat")
    a, u = r.read_field("a")[:, ::sub], r.read_field("u")[:, ::sub]
    return a[..., None], u[..., None]


GEN = os.environ.get("LOGOS_GEN", os.path.join(_ROOT, "gen"))


def darcy_notch(n, sub=2):
    """Generated by scripts/data/gen_darcy_notch.py (lu-group generator): boundary GP -> pressure, 101x101 -> 51x51.

    Outside-domain pixels follow the original nearest-neighbour fill; `notch_mask()` gives the domain.
    """
    d = np.load(f"{GEN}/darcy_notch/darcy_notch.npz")
    x = torch.from_numpy(d["boundCoeff"][:, ::sub, ::sub].copy())
    y = torch.from_numpy(d["sol"][:, ::sub, ::sub].copy())
    return x[..., None], y[..., None]


def notch_mask(sub=2):
    return torch.from_numpy(np.load(f"{GEN}/darcy_notch/darcy_notch.npz")["mask"][::sub, ::sub].copy())


def advection_paper(n, t_out=50):
    """Wave advection, generated by scripts/data/gen_advection.py (lu-group IC2): u(x, 0) -> u(x, t[t_out]), 200 points."""
    u = np.load(f"{GEN}/advection_ic2_200/advection_ic2.npz")["u"]
    return torch.from_numpy(u[:, 0].copy())[..., None], torch.from_numpy(u[:, t_out].copy())[..., None]


def darcy_std(n=None, sub=5):
    """Standard FNO/Transolver Darcy split at 85x85, ordered train smooth1[:1000], val smooth2[200:400], test smooth2[:200].

    Use with --ntrain 1000 --nval 200 --ntest 200. Training and test are exactly the published sets; the
    validation/calibration fields come from the unused part of smooth2, so calibration has 100 fields, not 12.
    """
    r1 = MatReader(f"{RAW}/hf_mutransfer/piececonst_r421_N1024_smooth1.mat")
    r2 = MatReader(f"{RAW}/fno/darcy421/piececonst_r421_N1024_smooth2.mat")
    f = lambda r, k: r.read_field(k)[:, ::sub, ::sub][..., None]
    c2, s2 = f(r2, "coeff"), f(r2, "sol")
    return torch.cat([f(r1, "coeff")[:1000], c2[200:400], c2[:200]]), torch.cat([f(r1, "sol")[:1000], s2[200:400], s2[:200]])


def _geo(prefix, out_idx, n):
    """Reordered as train [:1000], val [1200:1300] (unused by the protocol), test [1000:1200], so
    load_split(name, 1000, 100, 200) gives exactly the Geo-FNO/Transolver train and test sets."""
    X, Y, Q = (_npy(f"{prefix}_{k}.npy") for k in "XYQ")
    idx = np.r_[0:1000, 1200:1300, 1000:1200]
    x = torch.from_numpy(np.stack([X[idx], Y[idx]], -1)).float()
    return x, torch.from_numpy(np.ascontiguousarray(Q[idx, out_idx]))[..., None].float()


def airfoil(n=None):
    """Geo-FNO NACA airfoil: C-mesh (X, Y), 221x51 -> Mach number. Standard: first 1000 train, [1000:1200] test."""
    return _geo(f"{RAW}/geofno/airfoil/naca/NACA_Cylinder", 4, n)


def ns1024(n=None, sub=1):
    """Kossaifi et al. (neuraloperator Zenodo): forcing -> vorticity (Re=500, T=5), 1024x1024, 1000 train + 1000 test fields.
    The two official files are concatenated (train first), so use tail_test=True to test on the official test file.
    sub > 1 keeps every sub-th grid point per axis (1024 / sub)."""
    out = []
    for split in ("train", "test"):
        d = torch.load(f"{RAW}/zenodo/ns1024/nsforcing_1024_{split}.pt", mmap=True, weights_only=True)   # tensors only
        out.append((d["x"][:, ::sub, ::sub].clone()[..., None], d["y"][:, ::sub, ::sub].clone()[..., None]))
    x, y = torch.cat([o[0] for o in out]), torch.cat([o[1] for o in out])
    return (x, y) if n is None else (x[:n], y[:n])


def co2_sg(n=None):
    """Wen et al. 2022 (U-FNO), CO2 storage: gas saturation over 24 snapshots on a 96 x 200 radial grid.
    Input: the 11 time-independent channels at t = 0 (reservoir fields, scalar injection parameters, r and z
    coordinates; the time channel is dropped), (96, 200, 11). Output: saturation, one channel per snapshot, (96, 200, 24).
    Ordered train (4500), val (500), test (500) from the official files: use load_split(name, 4500, 500, 500)."""
    cache = f"{RAW}/ufno/cache_sg_xt0.pt"              # the t=0 input slice touches the whole 100 GB file: do it once
    if not os.path.exists(cache):
        xs = [torch.load(f"{RAW}/ufno/sg_{s}_a.pt", mmap=True, weights_only=True)[:, :, :, 0, :11].clone()
              for s in ("train", "val", "test")]
        torch.save(torch.cat(xs), cache)
    x = torch.load(cache, weights_only=True)
    y = torch.cat([torch.load(f"{RAW}/ufno/sg_{s}_u.pt", mmap=True, weights_only=True).clone() for s in ("train", "val", "test")])
    return (x, y) if n is None else (x[:n], y[:n])


REGISTRY = {"burgers": burgers, "advection_paper": advection_paper, "darcy_notch": darcy_notch, "ns_forcing": ns_forcing,
            "darcy_std": darcy_std, "airfoil": airfoil, "co2_sg": co2_sg, "ns1024": ns1024}


def _resolve(name):
    """'base' or 'base@sub=k' (grid-resolution sweeps). Loaders with a `sub` argument (Burgers, Darcy notch) take k as
    their stride from the stored resolution; for the others every k-th point along each spatial axis is kept."""
    base, _, opt = name.partition("@sub=")
    if not opt:
        return REGISTRY[base]
    k, f = int(opt), REGISTRY[base]
    if "sub" in inspect.signature(f).parameters:
        return lambda n: f(n, sub=k)

    def strided(n):
        x, y = f(n)
        idx = (slice(None),) + (slice(None, None, k),) * (x.ndim - 2)
        return x[idx].contiguous(), y[idx].contiguous()
    return strided


def domain_mask(name):
    """Physical-domain mask (flattened grid) for masked benchmarks, None otherwise."""
    base, _, opt = name.partition("@sub=")
    return notch_mask(int(opt) if opt else 2).flatten().bool() if base == "darcy_notch" else None


def load_split(name, ntrain, nval, ntest, tail_test=False):
    """Disjoint train/val/test. tail_test takes test from the end of the file."""
    f = _resolve(name)
    x, y = f(ntrain + nval + ntest) if not tail_test else f(None)
    tr = torch.arange(ntrain)
    va = torch.arange(ntrain, ntrain + nval)
    te = torch.arange(len(x) - ntest, len(x)) if tail_test else torch.arange(ntrain + nval, ntrain + nval + ntest)
    return (x[tr], y[tr]), (x[va], y[va]), (x[te], y[te])
